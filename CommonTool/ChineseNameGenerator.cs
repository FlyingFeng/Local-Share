        /// <summary>
        /// 生成随机标识名：形容词 + 名词
        /// </summary>
        /// <param name="count">字数：2（各一字）/ 4（各两字）</param>
        public static string Generate(NameLength length = NameLength.Two)
        {
            return length switch
            {
                NameLength.Two => GenerateTwo(),   // 一形 + 一名
                NameLength.Four => GenerateFour(),  // 二形 + 二名
                _ => GenerateTwo()
            };
        }

        /// <summary>
        /// 批量生成，自动去重
        /// </summary>
        public static List<string> GenerateBatch(int count, NameLength length = NameLength.Two)
        {
            var result = new HashSet<string>();
            var maxAttempts = count * 10;
            var attempts = 0;

            while (result.Count < count && attempts < maxAttempts)
            {
                result.Add(Generate(length));
                attempts++;
            }

            return result.ToList();
        }

        // 一字形容词 + 一字名词
        private static string GenerateTwo()
        {
            var adj = Adjectives[_random.Next(Adjectives.Length)];
            var noun = Nouns[_random.Next(Nouns.Length)];

            // 避免两字相同
            while (noun == adj)
                noun = Nouns[_random.Next(Nouns.Length)];

            return adj + noun;
        }

        // 两字形容词 + 两字名词
        private static string GenerateFour()
        {
            var adj1 = Adjectives[_random.Next(Adjectives.Length)];
            var adj2 = Adjectives[_random.Next(Adjectives.Length)];
            while (adj2 == adj1)
                adj2 = Adjectives[_random.Next(Adjectives.Length)];

            var noun1 = Nouns[_random.Next(Nouns.Length)];
            var noun2 = Nouns[_random.Next(Nouns.Length)];
            while (noun2 == noun1)
                noun2 = Nouns[_random.Next(Nouns.Length)];

            return adj1 + adj2 + noun1 + noun2;
        }
